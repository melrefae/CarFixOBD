  static List<WorldwideBrand> filter({String region = 'All Regions', String query = ''}) {
    var list = allBrands;
    if (region != 'All Regions') {
      list = list.where((b) => b.region.toLowerCase() == region.toLowerCase()).toList();
    }
    if (query.trim().isNotEmpty) {
      final q = query.trim().toLowerCase();
      list = list.where((b) {
        return b.name.toLowerCase().contains(q) ||
            b.nameAr.contains(q) ||
            b.country.toLowerCase().contains(q);
      }).toList();
    }
    return list;
  }
