/// Status of an individual diagnostic parameter in a test stage
enum StageParameterStatus {
  normal,
  warning,
  critical,
}

/// Detailed telemetry or threshold parameter inspected within a test stage
class StageParameterDetail {
  final String nameEn;
  final String nameAr;
  final String value;
  final String unit;
  final String nominalRange;
  final StageParameterStatus status;
  final double? currentNumeric;
  final double? minNominal;
  final double? maxNominal;
  final double? minRange;
  final double? maxRange;

  const StageParameterDetail({
    required this.nameEn,
    required this.nameAr,
    required this.value,
    this.unit = "",
    this.nominalRange = "",
    this.status = StageParameterStatus.normal,
    this.currentNumeric,
    this.minNominal,
    this.maxNominal,
    this.minRange,
    this.maxRange,
  });

  String getName(bool isAr) => isAr ? nameAr : nameEn;
}

/// Single diagnostic stage item in the comprehensive 16-stage test suite
class FullTestStageResult {
  final int stageNumber;
  final String titleEn;
  final String titleAr;
  final String descriptionEn;
  final String descriptionAr;
  final String category;
  final bool isCompleted;
  final bool isPassed;
  final bool hasWarning;
  final String statusDetailEn;
  final String statusDetailAr;
  final String technicalExplanationEn;
  final String technicalExplanationAr;
  final String recommendationEn;
  final String recommendationAr;
  final String rawCommand;
  final String rawHexResponse;
  final List<StageParameterDetail> parameters;
  final String? actionTarget;

  const FullTestStageResult({
    required this.stageNumber,
    required this.titleEn,
    required this.titleAr,
    required this.descriptionEn,
    required this.descriptionAr,
    this.category = "Diagnostics",
    this.isCompleted = false,
    this.isPassed = true,
    this.hasWarning = false,
    this.statusDetailEn = "",
    this.statusDetailAr = "",
    this.technicalExplanationEn = "",
    this.technicalExplanationAr = "",
    this.recommendationEn = "",
    this.recommendationAr = "",
    this.rawCommand = "",
    this.rawHexResponse = "",
    this.parameters = const [],
    this.actionTarget,
  });

  String getTitle(bool isAr) => isAr ? titleAr : titleEn;
  String getDescription(bool isAr) => isAr ? descriptionAr : descriptionEn;
  String getStatusDetail(bool isAr) => isAr ? statusDetailAr : statusDetailEn;
  String getTechnicalExplanation(bool isAr) => isAr ? technicalExplanationAr : technicalExplanationEn;
  String getRecommendation(bool isAr) => isAr ? recommendationAr : recommendationEn;

  FullTestStageResult copyWith({
    bool? isCompleted,
    bool? isPassed,
    bool? hasWarning,
    String? statusDetailEn,
    String? statusDetailAr,
    String? category,
    String? technicalExplanationEn,
    String? technicalExplanationAr,
    String? recommendationEn,
    String? recommendationAr,
    String? rawCommand,
    String? rawHexResponse,
    List<StageParameterDetail>? parameters,
    String? actionTarget,
  }) {
    return FullTestStageResult(
      stageNumber: stageNumber,
      titleEn: titleEn,
      titleAr: titleAr,
      descriptionEn: descriptionEn,
      descriptionAr: descriptionAr,
      category: category ?? this.category,
      isCompleted: isCompleted ?? this.isCompleted,
      isPassed: isPassed ?? this.isPassed,
      hasWarning: hasWarning ?? this.hasWarning,
      statusDetailEn: statusDetailEn ?? this.statusDetailEn,
      statusDetailAr: statusDetailAr ?? this.statusDetailAr,
      technicalExplanationEn: technicalExplanationEn ?? this.technicalExplanationEn,
      technicalExplanationAr: technicalExplanationAr ?? this.technicalExplanationAr,
      recommendationEn: recommendationEn ?? this.recommendationEn,
      recommendationAr: recommendationAr ?? this.recommendationAr,
      rawCommand: rawCommand ?? this.rawCommand,
      rawHexResponse: rawHexResponse ?? this.rawHexResponse,
      parameters: parameters ?? this.parameters,
      actionTarget: actionTarget ?? this.actionTarget,
    );
  }
}

/// Comprehensive vehicle health analysis model generated by 1-Click Full Vehicle Test
class FullTestResult {
  final int healthScore; // 0 to 100
  final String healthRatingEn;
  final String healthRatingAr;
  final String vin;
  final String protocol;
  final double batteryVoltage;
  final bool isMilOn;
  final int dtcCount;
  final List<DtcModel> allDtcs;
  final List<EcuModuleNode> ecuModules;
  final ReadinessMonitors? readiness;
  final BatteryHealthResult? batteryHealth;
  final FuelTrimAnalysisResult? fuelTrimHealth;
  final CatalyticHealthReport? catalyticHealth;
  final bool sgwLocked;
  final Map<String, String> liveSensors;
  final InspectionReport report;
  final List<FullTestStageResult> stages;
  final DateTime completedAt;

  FullTestResult({
    required this.healthScore,
    required this.healthRatingEn,
    required this.healthRatingAr,
    required this.vin,
    required this.protocol,
    required this.batteryVoltage,
    required this.isMilOn,
    required this.dtcCount,
    required this.allDtcs,
    required this.ecuModules,
    this.readiness,
    this.batteryHealth,
    this.fuelTrimHealth,
    this.catalyticHealth,
    required this.sgwLocked,
    required this.liveSensors,
    required this.report,
    required this.stages,
    required this.completedAt,
  });

  String getHealthRating(bool isAr) => isAr ? healthRatingAr : healthRatingEn;
}
